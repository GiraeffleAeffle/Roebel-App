/**
 * Postgres bootstrap. The image only creates the default superuser; every service
 * that shares this database (Nextcloud, Synapse, XWiki, OpenProject) needs its OWN
 * role and database, or it fails with "password authentication failed for user X".
 * Runs once, on first initialisation of an empty data directory.
 */
/**
 * NSP-9 peer sync loop.
 *
 * One `strfry sync` per declared peer, on a loop. Negentropy (NIP-77) reconciles
 * SETS rather than streaming a log, so each pass transfers only the difference —
 * cost tracks what changed, not how much history exists — and a bidirectional
 * link cannot ping-pong, because an event either is in the store or is not.
 *
 * Filters are per-link: a peer carries exactly the kinds its manifest entry
 * declares, so widening what crosses the boundary is always a visible edit.
 *
 * A failing peer must never stop the others: an unreachable node is a normal
 * condition in a federation, not an error worth halting a sweep for.
 */
export function renderFederationSync(m: NetizenManifest, intervalSeconds = 300): string {
  const peers = m.peers ?? [];
  const lines = peers.map((p) => {
    const filter = JSON.stringify({ kinds: p.kinds });
    return [
      `  echo "[$(date -u +%FT%TZ)] pull ${p.id} ${p.relay}"`,
      `  /app/strfry --config=/etc/strfry-mirror-sync.conf sync "${p.relay}" \\`,
      `    --dir down --filter '${filter}' \\`,
      `    || echo "[$(date -u +%FT%TZ)] peer ${p.id} unreachable — continuing"`,
    ].join("\n");
  });

  return `#!/bin/sh
# Generated by \`netizen render\` — NSP-9 federation for node "${m.id}".
#
# Pulls the PUBLIC record of declared peers into this node's federation MIRROR,
# which is a separate store from the members-only authoring relay. Two reasons:
#
#  1. \`strfry sync\` enforces the destination's write policy (verified 2026-07-28:
#     a synced event arrives as sourceType IP4 and is indistinguishable from a
#     stranger publishing). Writing peers into the authoring relay would mean
#     weakening the members-only gate that relay exists to enforce.
#  2. PULL-ONLY: this node never writes into a peer's database. Each node decides
#     what it ingests, and both ends still converge on the same set.
#
# Every peer and kind comes from the manifest. This file is never where trust is
# edited. The binary is addressed absolutely: it is not on PATH in this image.
set -u

while true; do
${lines.join("\n") || '  echo "no peers declared"'}
  sleep ${intervalSeconds}
done
`;
}

/**
 * The federation mirror's relay config — serves READS of peers' public events.
 *
 * Same LMDB store as the syncer, but a DIFFERENT config: this one installs a
 * reject-everything write policy. That is what makes the mirror publicly
 * readable without being publicly writable, because a policy that blocks
 * strangers would otherwise block the syncer too — both arrive as plain IP4
 * writes and strfry cannot tell them apart.
 */
export function renderMirrorConf(m: NetizenManifest): string {
  return `${header(m, "Nostr federation mirror (read-only)")}db = "/app/mirror-db/"
relay {
  bind = "0.0.0.0"
  port = 7777
  info {
    name = "${m.name} Federation Mirror"
    description = "Public events mirrored from ${m.id}'s declared peers. Read-only."
  }
  writePolicy { plugin = "/etc/strfry-mirror/reject-all.sh" }
}
`;
}

