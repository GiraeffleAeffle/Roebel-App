/** Caddy reverse proxy for every service subdomain the manifest declares (auto TLS). */
export function renderCaddyfile(m: NetizenManifest): string {
  const blocks: string[] = [];
  const add = (u: string | undefined, upstream: string) => {
    if (u) blocks.push(`${hostname(u)} {\n  reverse_proxy ${upstream}\n}`);
  };
  // Only route the IdP locally when this node actually hosts it. An externally
  // hosted keystone (e.g. on Fly) resolves via its own DNS/TLS — routing it here
  // would blackhole logins for every service on the node.
  if (m.identity && m.identity.idp.hosted !== "external") add(m.identity.idp.issuer, "roebel-id:3010");
  const ws = m.services.workspace;
  if (ws?.nextcloud && ws.collabora) {
    // Collabora shares the Nextcloud host: its own paths go to the editor, the
    // rest to Nextcloud. Same-origin keeps WOPI simple and needs no extra DNS
    // record or certificate. (Without this the Office app 404s — the editor is
    // running but unreachable.)
    // `handle` blocks are mutually exclusive and evaluated in written order.
    // Two bare `reverse_proxy` directives do NOT preserve order in Caddy — the
    // Collabora paths silently fell through to Nextcloud and Office 404'd.
    blocks.push(`${hostname(ws.nextcloud)} {
  handle /browser/* {
    reverse_proxy collabora:9980
  }
  handle /hosting/* {
    reverse_proxy collabora:9980
  }
  handle /cool/* {
    reverse_proxy collabora:9980
  }
  handle {
    reverse_proxy nextcloud:80
  }
}`);
  } else {
    add(ws?.nextcloud, "nextcloud:80");
  }
  add(ws?.mail, "ox:8080"); // Open-Xchange
  add(ws?.wiki, "xwiki:8080");
  add(ws?.video, "jitsi:8000");
  add(ws?.project, "openproject:80");
  // NOTE: `portal` is a link target for the agent-workspace tile, not a service
  // this installer provisions yet — no Caddy route until something backs it.
  add(m.services.chat?.matrix?.homeserver, "synapse:8008");
  add(m.services.chat?.matrix?.mas, "mas:8080");
  add(m.services.chat?.matrix?.element, "element:80");
  const relay = m.services.chat?.nostr?.relay;
  if (relay) blocks.push(`${hostname(relay)} {\n  reverse_proxy strfry:7777\n}`);
  return header(m, "Caddy reverse proxy (auto TLS)") + "\n" + blocks.join("\n\n") + "\n";
}

/** The deployable stack — every service this node declares, and nothing else. */
export function renderComposeYml(m: NetizenManifest): string {
  const hasMatrix = !!m.services.chat?.matrix;
  const hasNostr = !!m.services.chat?.nostr;
  // An externally hosted keystone (identity.idp.hosted === "external") is NOT
  // provisioned here: starting a second one would shadow the real issuer.
  const hostsIdp = !!m.identity && m.identity.idp.hosted !== "external";
  const svc: string[] = [
    `  caddy:
    image: caddy:2
    restart: unless-stopped
    ports: ["80:80", "443:443"]
    volumes: ["./Caddyfile:/etc/caddy/Caddyfile", "caddy_data:/data"]`,
  ];
  if (hostsIdp) {
    svc.push(`  roebel-id:
    image: \${ROEBEL_ID_IMAGE:-ghcr.io/roebel-labs/roebel-id:latest}
    restart: unless-stopped
    env_file: ["./roebel-id.env"]
    expose: ["3010"]`);
  }
  if (hasMatrix) {
    svc.push(
      `  postgres:
    image: postgres:16
    restart: unless-stopped
    environment: { POSTGRES_PASSWORD: "\${POSTGRES_PASSWORD}" }
    volumes:
      - "pg_data:/var/lib/postgresql/data"
      - "./postgres/init:/docker-entrypoint-initdb.d:ro"`,
      `  synapse:
    image: matrixdotorg/synapse:latest
    restart: unless-stopped
    environment:
      SYNAPSE_CONFIG_PATH: /data/homeserver.yaml
    volumes:
      - "synapse_data:/data"
      - "./synapse/homeserver.rendered.yaml:/data/homeserver.yaml:ro"
    depends_on: [postgres, mas]
    expose: ["8008"]`,
      `  mas:
    image: ghcr.io/element-hq/matrix-authentication-service:latest
    restart: unless-stopped
    command: ["server", "--config", "/config.yaml"]
    volumes:
      - "./mas/config.rendered.yaml:/config.yaml:ro"
      - "./matrix/keys:/keys:ro"
    depends_on: [postgres]
    expose: ["8080"]`,
      `  element:
    image: vectorim/element-web:latest
    restart: unless-stopped
    volumes: ["./element/config.json:/app/config.json"]
    expose: ["80"]`,
    );
  }
  if (hasNostr) {
    // The relay mounts the POLICY DIRECTORY (not single files): editors/sed -i
    // replace inodes, and a single-file bind mount would keep the stale inode,
    // so live grants/revokes of the write allow-list would silently not apply.
    svc.push(
      `  strfry:
    image: ghcr.io/hoytech/strfry:latest
    restart: unless-stopped
    command: relay
    volumes:
      - "./strfry.conf:/etc/strfry.conf"
      - "./strfry-policy:/etc/strfry:ro"
      - "strfry_db:/app/strfry-db"
    expose: ["7777"]`,
    );
    // The allow-list syncer: on-chain CitizenNFT membership -> relay write access,
    // so admission and revocation are automatic rather than a hand-run script.
    // It mounts the SAME policy directory as the relay but WRITABLE (the relay
    // gets :ro), and it only reaches out — no inbound surface added to the box.
    if (m.services.backend && m.contracts) {
      const agentKeys = m.agents?.a2a?.relayPubkeys ?? [];
      svc.push(
        `  relay-sync:
    image: node:22-alpine
    restart: unless-stopped
    command: ["node", "/app/relay-sync.cjs"]
    volumes:
      - "./relay-sync/relay-sync.cjs:/app/relay-sync.cjs:ro"
      - "./strfry-policy:/etc/strfry"
    environment:
      SUPABASE_URL: "\${SUPABASE_URL}"
      # Service-role key: reads the private wallet<->npub registry. Never in the
      # bundle or in git — it comes from the box's own .env.
      SUPABASE_SERVICE_KEY: "\${SUPABASE_SERVICE_KEY}"
      GNOSIS_RPC_URL: "\${GNOSIS_RPC}"
      CITIZEN_NFT_ADDRESS: "${m.contracts!.citizenNft}"
      ALLOWLIST_PATH: "/etc/strfry/members.txt"
      SYNC_INTERVAL_SECONDS: "300"
      # This node's own agents. Their key is NIP-06 derived from an agent smart
      # account holding no CitizenNFT, so without this the syncer would erase
      # them every pass and no agent could publish to its own community's relay.
      AGENT_PUBKEYS: "${agentKeys.join(",")}"
    depends_on: [strfry]`,
      );
    }

    // NSP-9 federation: mirror declared peers' public events over NIP-77
    // negentropy. Runs `strfry sync` inside the relay's own container image so it
    // shares the binary and the store; pull-based, so no inbound surface is added.
    if (m.peers?.length) {
      // The mirror is a SEPARATE store from the authoring relay, so federating
      // never weakens the members-only write gate. It serves reads; its content
      // arrives only from the syncer beside it.
      svc.push(
        `  mirror:
    image: ghcr.io/hoytech/strfry:latest
    restart: unless-stopped
    command: relay
    entrypoint: ["/app/strfry", "--config=/etc/strfry-mirror/mirror.conf"]
    volumes:
      - "./strfry-mirror:/etc/strfry-mirror:ro"
      - "mirror_db:/app/mirror-db"
    expose: ["7777"]`,
        `  federation:
    image: ghcr.io/hoytech/strfry:latest
    restart: unless-stopped
    entrypoint: ["/bin/sh", "/etc/strfry-mirror/sync-peers.sh"]
    volumes:
      - "./strfry-mirror:/etc/strfry-mirror:ro"
      - "./strfry-mirror/mirror-sync.conf:/etc/strfry-mirror-sync.conf:ro"
      - "mirror_db:/app/mirror-db"
    depends_on: [mirror]`,
      );
    }
  }

  // ---- Workspace (the openDesk-equivalent suite). Each is provisioned only
  // when the manifest declares its URL, so every node picks its own subset.
  const ws = m.services.workspace;
  if (ws?.nextcloud) {
    svc.push(
      `  nextcloud:
    image: nextcloud:stable
    restart: unless-stopped
    environment:
      POSTGRES_HOST: postgres
      POSTGRES_DB: nextcloud
      POSTGRES_USER: nextcloud
      POSTGRES_PASSWORD: "\${POSTGRES_PASSWORD}"
      NEXTCLOUD_TRUSTED_DOMAINS: "${hostname(ws.nextcloud)}"
      OVERWRITEPROTOCOL: https
    volumes: ["nextcloud_data:/var/www/html"]
    depends_on: [postgres]
    expose: ["80"]`,
    );
    if (ws.collabora) {
      svc.push(
        `  collabora:
    image: collabora/code:latest
    restart: unless-stopped
    environment:
      aliasgroup1: "https://${hostname(ws.nextcloud)}"
      DONT_GEN_SSL_CERT: "true"
      extra_params: "--o:ssl.enable=false --o:ssl.termination=true"
    expose: ["9980"]`,
      );
    }
  }
  if (ws?.mail) {
    svc.push(
      `  ox:                      # Open-Xchange (mail/calendar/contacts)
    image: \${OX_IMAGE:-openexchange/appsuite:latest}
    restart: unless-stopped
    depends_on: [postgres]
    expose: ["8080"]
    # NOTE: OX needs an IMAP/SMTP backend + its own provisioning — see PLAN.md`,
    );
  }
  if (ws?.wiki) {
    svc.push(
      `  xwiki:
    image: xwiki:stable-postgres-tomcat
    restart: unless-stopped
    environment:
      DB_USER: xwiki
      DB_PASSWORD: "\${POSTGRES_PASSWORD}"
      DB_HOST: postgres
    volumes: ["xwiki_data:/usr/local/xwiki"]
    depends_on: [postgres]
    expose: ["8080"]`,
    );
  }
  if (ws?.video) {
    svc.push(
      `  jitsi:                   # single-container Jitsi Meet (web + prosody + jicofo + jvb)
    image: jitsi/web:stable
    restart: unless-stopped
    environment:
      PUBLIC_URL: "${ws.video}"
      ENABLE_AUTH: "1"
      AUTH_TYPE: jwt          # tokens minted from the Röbel ID session
    expose: ["80"]
    # NOTE: full Jitsi needs prosody/jicofo/jvb sidecars + UDP 10000 — see PLAN.md`,
    );
  }
  if (ws?.project) {
    svc.push(
      `  openproject:
    image: openproject/openproject:14
    restart: unless-stopped
    environment:
      OPENPROJECT_HOST__NAME: "${hostname(ws.project)}"
      OPENPROJECT_HTTPS: "true"
      DATABASE_URL: "postgres://openproject:\${POSTGRES_PASSWORD}@postgres/openproject"
    volumes: ["openproject_data:/var/openproject/assets"]
    depends_on: [postgres]
    expose: ["80"]`,
    );
  }

  // ---- Sovereign AI gateway (model routing; keeps egress under node policy).
  if (m.ai?.selfHosted) {
    svc.push(
      `  litellm:                 # AI gateway — routes models, enforces data-egress policy
    image: ghcr.io/berriai/litellm:main-latest
    restart: unless-stopped
    env_file: ["./.env"]
    volumes: ["./ai/litellm.yaml:/app/config.yaml"]
    command: ["--config", "/app/config.yaml"]
    expose: ["4000"]`,
    );
  }

  // Postgres backs Matrix, Nextcloud, XWiki and OpenProject — include it if any need it.
  const needsPostgres =
    hasMatrix || !!ws?.nextcloud || !!ws?.wiki || !!ws?.project || !!ws?.mail;
  // (hasMatrix already emitted postgres above; append it here for the other cases.
  // Order within `services:` is irrelevant to compose — depends_on drives startup.)
  if (needsPostgres && !hasMatrix) {
    svc.push(`  postgres:
    image: postgres:16
    restart: unless-stopped
    environment: { POSTGRES_PASSWORD: "\${POSTGRES_PASSWORD}" }
    volumes:
      - "pg_data:/var/lib/postgresql/data"
      - "./postgres/init:/docker-entrypoint-initdb.d:ro"`);
  }

  const vols = ["caddy_data:"];
  if (needsPostgres) vols.push("pg_data:");
  if (hasNostr) vols.push("strfry_db:");
  // The federation mirror keeps its own store: peers' events never mingle with
  // what this node's own members authored.
  if (hasNostr && m.peers?.length) vols.push("mirror_db:");
  if (hasMatrix) vols.push("synapse_data:");
  if (ws?.nextcloud) vols.push("nextcloud_data:");
  if (ws?.wiki) vols.push("xwiki_data:");
  if (ws?.project) vols.push("openproject_data:");

  return `# Generated by \`netizen render\` — the sovereign node stack for "${m.id}".
# One command brings up everything this node declares: identity, comms, workspace,
# and AI. Services appear only when the manifest declares them.
# Secrets come from ./.env (see SECRETS.md) — never from this file.
services:
${svc.join("\n")}
volumes:
${vols.map((v) => `  ${v}`).join("\n")}
`;
}

/**
 * The Nostr write policy — CitizenNFT-gated. Rendered by the installer so every
 * node gets the same members-only relay without hand-wiring it (reads stay open).
 * Mirrors packages/cli/policies/nostr-citizen-write/.
 */
export function renderNostrPolicyAwk(m: NetizenManifest): string {
  return `# Generated by \`netizen render\` — write policy for node "${m.id}".
# Accept an EVENT only if its author pubkey is in the members allow-list.
# Re-reads the list per event (live grants/revokes) and fflush()es so strfry
# never blocks on a buffered pipe. Reads are unaffected.
{
  line = $0
  if (!match(line, /"id":"[0-9a-fA-F]{64}"/)) next
  id = substr(line, RSTART + 6, 64)
  pk = ""
  if (match(line, /"pubkey":"[0-9a-fA-F]{64}"/)) pk = tolower(substr(line, RSTART + 10, 64))
  allowed = 0
  if (pk != "") {
    while ((getline p < "/etc/strfry/members.txt") > 0) {
      gsub(/[ \\t\\r\\n]/, "", p)
      if (p != "" && substr(p, 1, 1) != "#" && tolower(p) == pk) { allowed = 1; break }
    }
    close("/etc/strfry/members.txt")
  }
  if (allowed)
    printf("{\\"id\\":\\"%s\\",\\"action\\":\\"accept\\"}\\n", id)
  else
    printf("{\\"id\\":\\"%s\\",\\"action\\":\\"reject\\",\\"msg\\":\\"blocked: only ${m.name} members may publish to this relay\\"}\\n", id)
  fflush()
}
`;
}

