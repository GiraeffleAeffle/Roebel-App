export function renderPostgresInit(m: NetizenManifest): string {
  const dbs = postgresDatabases(m);
  const lines = dbs
    .map((d) => {
      const createDb =
        d === "synapse"
          ? `CREATE DATABASE synapse OWNER synapse ENCODING 'UTF8' LC_COLLATE='C' LC_CTYPE='C' TEMPLATE template0`
          : `CREATE DATABASE ${d} OWNER ${d}`;
      return `ensure_role ${d}
ensure_db ${d} "${createDb}"`;
    })
    .join("\n");
  return `#!/bin/bash
# Generated by netizen render — per-service roles + databases for node "${m.id}".
#
# Runs BOTH as a docker-entrypoint-initdb.d script (fresh cluster) AND from
# bootstrap on every apply. The entrypoint hook only fires when the data
# directory is EMPTY, so a service added later would never get its role — which
# is exactly how Matrix failed with 'password authentication failed for user
# "mas"' on a cluster first initialised when only Nextcloud existed.
# Every step is idempotent, so re-running is always safe.
set -e
PSQL="psql -v ON_ERROR_STOP=1 --username \${POSTGRES_USER:-postgres} --no-psqlrc -tAc"

ensure_role() {   # ensure_role <name>
  if [ "$($PSQL "SELECT 1 FROM pg_roles WHERE rolname='$1'")" = "1" ]; then
    $PSQL "ALTER ROLE $1 WITH LOGIN PASSWORD '\${POSTGRES_PASSWORD}'" >/dev/null
  else
    $PSQL "CREATE ROLE $1 LOGIN PASSWORD '\${POSTGRES_PASSWORD}'" >/dev/null
    echo "created role $1"
  fi
}

ensure_db() {     # ensure_db <name> <create-statement>
  if [ "$($PSQL "SELECT 1 FROM pg_database WHERE datname='$1'")" != "1" ]; then
    $PSQL "$2" >/dev/null
    echo "created database $1"
  fi
}

${lines || "true"}
echo "postgres: roles and databases ready"
`;
}

