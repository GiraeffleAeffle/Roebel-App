/** Idempotent on-box apply script. Run by `netizen up` (or by hand). Re-runnable. */
export function renderBootstrap(m: NetizenManifest): string {
  const hasNextcloud = !!m.services.workspace?.nextcloud;
  const nc = hasNextcloud
    ? `
# 4. Nextcloud OIDC provider + group folders (once the container is initialized).
if docker compose ps --services 2>/dev/null | grep -qx nextcloud; then
  docker compose exec -T -u www-data \\
    -e NEXTCLOUD_CLIENT_SECRET="$NEXTCLOUD_CLIENT_SECRET" \\
    nextcloud sh < nextcloud/setup.sh \\
    || echo "note: re-run once Nextcloud finished its first-run install"
fi`
    : "";
  // Durability + hardening. Installed here rather than hand-run, so node #2
  // inherits them instead of repeating node #1's gap.
  const ops = [
    m.operations?.backup
      ? `
# 5. Backups. Install the systemd timer (idempotent) — chosen over cron because
# it records a real last-run status the operator (and an agent) can read back.
chmod +x ops/backup.sh ops/restore.sh
install -m 644 ops/netizen-backup.service /etc/systemd/system/netizen-backup.service
install -m 644 ops/netizen-backup.timer   /etc/systemd/system/netizen-backup.timer
systemctl daemon-reload
systemctl enable --now netizen-backup.timer
echo "backup timer: $(systemctl is-active netizen-backup.timer) — next: $(systemctl show -p NextElapseUSecRealtime --value netizen-backup.timer)"`
      : "",
    m.operations?.hardening
      ? `
# 6. Host hardening (SSH policy, fail2ban). Idempotent; refuses to lock you out.
# Its exit status is carried to the END of bootstrap rather than aborting here:
# the rest of the node is already up, and a hardening problem must be reported
# loudly (non-zero \`netizen up\`) instead of silently swallowed.
chmod +x ops/harden.sh
HARDEN_RC=0
bash ops/harden.sh || HARDEN_RC=$?`
      : "",
  ]
    .filter(Boolean)
    .join("\n");
  return `#!/usr/bin/env bash
# Generated by \`netizen render\` — idempotent apply for node "${m.id}". Run ON the box (Ubuntu, sudo).
# Safe to re-run: docker compose converges; every step is create-if-absent.
set -euo pipefail
cd "$(dirname "$0")"

# 1. Docker engine + the compose plugin. Checked SEPARATELY: a box can have
# docker without the plugin, and skipping on \`docker\` alone leaves \`docker
# compose\` broken.
if ! command -v docker >/dev/null 2>&1; then
  apt-get update && apt-get -y install docker.io
  systemctl enable --now docker
fi
if ! docker compose version >/dev/null 2>&1; then
  apt-get update && apt-get -y install docker-compose-plugin \\
    || apt-get -y install docker-compose-v2 \\
    || { echo "ERROR: could not install the docker compose plugin" >&2; exit 1; }
fi

# 2. Secrets — a .env next to this script must supply the refs listed in SECRETS.md.
if [ ! -f .env ]; then
  echo "ERROR: create .env from SECRETS.md (POSTGRES_PASSWORD, ROEBEL_ID_JWKS, ...) before applying." >&2
  echo "Tip: for a secret-free first light, run just the Nostr relay: docker compose up -d strfry" >&2
  exit 1
fi
set -a; . ./.env; set +a

# 2b. Matrix: generate secrets/keys on the box, then substitute them into the
# rendered configs. Synapse and MAS need real values in their YAML (neither reads
# env vars), so the bundle ships \${PLACEHOLDER} templates and we fill them here —
# secrets therefore never exist in the bundle or in git.
if [ -f matrix/generate-secrets.sh ]; then
  bash matrix/generate-secrets.sh
  set -a; . ./.env; set +a
  command -v envsubst >/dev/null 2>&1 || apt-get update -qq && apt-get -y install gettext-base >/dev/null 2>&1 || true
  envsubst < mas/config.yaml            > mas/config.rendered.yaml
  envsubst < synapse/homeserver.yaml    > synapse/homeserver.rendered.yaml
  # Synapse and MAS drop to a NON-ROOT user inside their containers, so a 600
  # root-owned file is unreadable to them and they crash-loop with
  # "Permission denied". The secrets stay protected by the deploy directory
  # being root-owned 700 (below): dockerd is root and can bind-mount the file,
  # while non-root users on the host cannot traverse into the directory.
  chmod 644 mas/config.rendered.yaml synapse/homeserver.rendered.yaml
  chmod 644 matrix/keys/*.pem 2>/dev/null || true
fi

# 2b-bis. The relay write-policy plugin must be EXECUTABLE.
# strfry runs it as a program, and a bundle copied by rsync/scp can easily arrive
# without the exec bit. When the plugin cannot start, strfry fails CLOSED and
# rejects every event with "internal error" — the relay looks alive, the
# allow-list looks correct, and nobody can publish. Cost a full debugging cycle
# on node #1; it is one chmod, so it belongs here rather than in a runbook.
if [ -d strfry-policy ]; then
  chmod +x strfry-policy/*.sh 2>/dev/null || true
fi

# 2c. Ensure every declared service has its Postgres role + database. The
# initdb.d hook only fires on an EMPTY data directory, so services added after
# first boot need this explicit pass against the running cluster.
if [ -f postgres/init/01-databases.sh ]; then
  docker compose up -d postgres >/dev/null 2>&1 || true
  for _ in $(seq 1 30); do
    docker compose exec -T postgres pg_isready -U postgres >/dev/null 2>&1 && break
    sleep 1
  done
  docker compose exec -T -e POSTGRES_PASSWORD="$POSTGRES_PASSWORD" postgres \\
    bash /docker-entrypoint-initdb.d/01-databases.sh || echo "note: database provisioning reported an issue"
fi

# 2d. Synapse drops to uid 991 inside its container but a fresh named volume is
# root-owned, so it cannot create its signing key. Fix ownership once, from a
# throwaway container, before Synapse starts.
if [ -f synapse/homeserver.rendered.yaml ]; then
  docker run --rm -v "$(basename "$PWD")_synapse_data:/data" alpine:3 \\
    sh -c 'chown -R 991:991 /data' >/dev/null 2>&1 || true
fi

# 3. Bring up the stack (idempotent).
docker compose up -d

# 3b. Restart Caddy. Its config is a bind mount, so "compose up -d" writes the new
# file but does NOT restart the container. "caddy reload" inside the container was
# observed to report success while continuing to serve the OLD routes, so restart
# is the only reliable way to apply routing changes (~1s of downtime).
docker compose restart caddy 2>/dev/null || true

${nc}
${ops}
echo "Applied node \\"${m.id}\\". Verify: docker compose ps"
${m.operations?.hardening ? 'exit "${HARDEN_RC:-0}"' : ""}
`;
}

/** Walk the manifest and collect every secret reference ($ENV / vault:), deduped. */
export function collectSecretRefs(m: NetizenManifest): string[] {
  const out = new Set<string>();
  const walk = (v: unknown) => {
    if (typeof v === "string") {
      if (/^\$[A-Z0-9_]+$/.test(v) || v.startsWith("vault:")) out.add(v);
    } else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  walk(m);
  return [...out].sort();
}

export function renderSecretsChecklist(m: NetizenManifest): string {
  const refs = collectSecretRefs(m);
  const items = refs.map((r) => `- [ ] \`${r}\``).join("\n");
  return `${header(m, "secrets the operator must supply before \`netizen up\`")}
These are **references** — supply the real values via env / vault at apply time.
They are never written into the bundle.

${items}
`;
}

export function plan(m: NetizenManifest): Step[] {
  const ws = m.services.workspace;
  const hosts = ["id", ...(ws?.nextcloud ? ["cloud"] : []), ...(m.services.chat?.matrix ? ["matrix", "auth", "chat"] : []),
    ...(m.services.chat?.nostr ? ["relay"] : []), ...(ws?.mail ? ["mail"] : []), ...(ws?.wiki ? ["wiki"] : []),
    ...(ws?.video ? ["meet"] : []), ...(ws?.project ? ["project"] : [])];
  const steps: Step[] = [];
  steps.push({ id: "dns", phase: "provision", title: `Point DNS at the box for: ${hosts.join(", ")}` });
  steps.push({ id: "secrets", phase: "provision", title: "Place .env on the box with every ref from SECRETS.md" });
  steps.push({ id: "compose", phase: "services", title: "docker compose up -d — brings up the whole declared stack" });
  // A node with no identity section has no keystone to stand up or verify.
  if (m.identity)
    steps.push(
      m.identity.idp.hosted === "external"
        ? { id: "identity", phase: "identity", title: `Keystone hosted externally at ${m.identity.idp.issuer} — verify discovery resolves; nothing to deploy here` }
        : { id: "roebel-id", phase: "identity", title: "Keystone live (roebel-id.env) — the single sign-in for every service below" },
  );
  if (rp(m, "nextcloud")) steps.push({ id: "nextcloud-oidc", phase: "workspace", title: "Run nextcloud/setup.sh (OIDC provider + group folder per org)" });
  if (ws?.mail) steps.push({ id: "mail-oidc", phase: "workspace", title: "Point Open-Xchange at the keystone (OIDC) + its IMAP/SMTP backend" });
  if (ws?.wiki) steps.push({ id: "wiki-oidc", phase: "workspace", title: "Enable the XWiki OIDC provider against the keystone" });
  if (ws?.video) steps.push({ id: "video-auth", phase: "workspace", title: "Jitsi JWT auth from the keystone session (+ prosody/jicofo/jvb, UDP 10000)" });
  if (ws?.project) steps.push({ id: "project-oidc", phase: "workspace", title: "Enable the OpenProject OIDC provider against the keystone" });
  if (m.services.chat?.matrix) steps.push({ id: "mas-oidc", phase: "chat", title: "Apply mas/config.yaml (upstream = the keystone) and restart MAS" });
  if (m.services.chat?.nostr) steps.push({ id: "nostr-relay", phase: "chat", title: "Nostr relay up behind Caddy, members-only writes (strfry-policy/)" });
  if (m.peers?.length)
    steps.push({
      id: "federation",
      phase: "chat",
      title: `Federation: mirror ${m.peers.length} declared peer(s) over NIP-77 negentropy`,
    });
  if (m.ai?.selfHosted) steps.push({ id: "ai-gateway", phase: "ai", title: "AI gateway (LiteLLM) up — model routing + data-egress policy" });
  steps.push({ id: "web-env", phase: "app", title: "Set web.env on the app host and redeploy (lights up the dashboard tiles)" });
  if (m.operations?.backup) {
    steps.push({ id: "backup", phase: "operations", title: `Enable netizen-backup.timer (${m.operations.backup.schedule ?? "02:30"} nightly)` });
    steps.push({ id: "backup-offsite", phase: "operations", title: "Set BACKUP_RESTIC_REPOSITORY + BACKUP_RESTIC_PASSWORD in .env — until then dumps never leave the box" });
    steps.push({ id: "backup-restore-test", phase: "operations", title: "TEST A RESTORE (ops/restore.sh). An untested backup is a belief, not a backup" });
  }
  if (m.operations?.hardening) steps.push({ id: "harden", phase: "operations", title: "Run ops/harden.sh (SSH keys-only, fail2ban)" });
  steps.push({ id: "firewall", phase: "operations", title: "Hetzner Cloud Firewall: allow 22/80/443 only — ufw cannot protect Docker-published ports" });
  steps.push({ id: "verify", phase: "verify", title: "doctor — discovery reachable, SSO round-trips, tiles light up" });
  return steps;
}

